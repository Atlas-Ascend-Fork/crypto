int main(int argc, char** argv)
{
    const int device = argc > 1 ? std::atoi(argv[1]) : 0;
    if (aclInit(nullptr) != ACL_SUCCESS) {
        return 1;
    }
    if (aclrtSetDevice(device) != ACL_SUCCESS) {
        (void)aclFinalize();
        return 1;
    }
    aclrtStream stream = nullptr;
    void* output = nullptr;
    aclError status = aclrtCreateStream(&stream);
    if (status == ACL_SUCCESS) {
        status = aclrtMalloc(&output, 16, ACL_MEM_MALLOC_HUGE_FIRST);
    }
    const std::array<uint8_t, 12> nonce{};
    std::array<uint8_t, 16> tag{};
    if (status == ACL_SUCCESS) {
        status = CannCryptoAes128Gcm(
            nullptr, 0, static_cast<uint8_t*>(output), 16, ROUND_KEYS.data(), nonce.data(), nullptr, 0, stream);
    }
    if (status == ACL_SUCCESS) {
        status = aclrtMemcpy(tag.data(), tag.size(), output, tag.size(), ACL_MEMCPY_DEVICE_TO_HOST);
    }
    if (output != nullptr) {
        (void)aclrtFree(output);
    }
    if (stream != nullptr) {
        (void)aclrtDestroyStream(stream);
    }
    (void)aclrtResetDevice(device);
    (void)aclFinalize();
    const std::array<uint8_t, 16> expected = {0x58, 0xe2, 0xfc, 0xce, 0xfa, 0x7e, 0x30, 0x61,
                                              0x36, 0x7f, 0x1d, 0x57, 0xa4, 0xe7, 0x45, 0x5a};
    const bool passed = status == ACL_SUCCESS && tag == expected;
    std::cout << (passed ? "AES_GCM_EXAMPLE=PASS" : "AES_GCM_EXAMPLE=FAIL") << '\n';
    return passed ? 0 : 1;
}
